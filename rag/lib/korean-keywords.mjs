/**
 * korean-keywords.mjs — 키워드 검색용 한국어 낱말 줄기 뽑기 (외부 형태소 분석기 없음)
 *
 * 왜 있나 (2026-10-03):
 *   RAG 키워드 쪽은 공백으로만 낱말을 자른다. 한국어는 조사·어미가 낱말에 붙어서
 *   "서버에서"·"로그인을"·"만료됐다"가 각각 "서버"·"로그인"·"만료"와 다른 낱말로 취급됐다.
 *   질의는 "로그인을"인데 글에는 "로그인이"만 있으면 키워드로는 영영 못 찾는다.
 *
 * 하는 일:
 *   - koreanStem(tok): 끝에 붙은 조사·어미 하나를 떼어 줄기를 낸다(긴 것부터 맞춘다).
 *     줄기가 2글자 미만이 되면 떼지 않는다 — "가는"→"가", "먹이"→"먹" 같은 오탐을 막는다.
 *   - keywordTokens(text): BM25 재채점용 토큰. 원래 토큰을 줄기로 바꿔 질의·문서 양쪽을 같은 규칙으로 맞춘다.
 *   - fuzzyStems(query): 색인 검색(FTS)에 "줄기 + 뒤 2글자까지" 질의를 걸 줄기 목록.
 *     색인은 그대로 두고(재색인 불필요) 질의 시점에만 넓힌다.
 *
 * 한계: 불규칙 활용("막혀서"↔"막히다")·합성어 분해는 못 한다. 조사·하다/되다류 어미에 집중했다.
 */

// 끝에 붙는 꼴. 긴 것이 먼저 맞도록 길이 내림차순으로 정렬해 쓴다.
