const SUFFIXES = [...new Set([...PARTICLES, ...ENDINGS])].sort((a, b) => b.length - a.length);

const HANGUL = /[가-힣]/;
const MIN_STEM = 2; // 줄기 최소 글자 수

// 일상 질의에 섞이는 군말. 색인 검색을 넓힐 때 이것까지 넓히면 잡음만 늘어난다.
const STOPWORDS = new Set([
  '어떻게', '어떤', '어디', '언제', '얼마', '얼마나', '무슨', '무엇', '뭐야', '뭐였지', '뭐였더라', '누가', '이유',
  '그거', '이거', '저거', '그것', '이것', '그때', '이번', '저번', '지난번', '아까', '다시', '그냥', '진짜', '정말',
  '우리', '내가', '제가', '그리고', '근데', '그런데', '관련', '대해', '대한', '있었지', '있었던', '있었어', '있어',
  '없어', '있는', '없는', '했던', '했었지', '했었어', '하라고', '했지', '했나', '했는지', '하는지', '했었나', '거야',
  '건가', '거지', '같은', '같아', '맞는', '얘기', '얘기야', '알려줘', '찾아줘', '보여줘', '있나', '있지',
]);

/** 끝의 조사·어미 하나를 뗀 줄기. 뗄 게 없거나 줄기가 너무 짧으면 null. */
export function koreanStem(token) {
  if (!token || !HANGUL.test(token.slice(-1))) return null;
  const chars = [...token];
  for (const suf of SUFFIXES) {
    if (!token.endsWith(suf)) continue;
    const stemChars = chars.slice(0, chars.length - [...suf].length);
    if (stemChars.length < MIN_STEM) continue; // 더 짧은 꼴로 다시 시도 ("하는"→X, "서버는"→"서버")
    return stemChars.join('');
  }
  return null;
}

/** 텍스트 → 낱말(소문자, 영숫자·한글만). 기존 _bm25Tokenize 와 같은 자르기 규칙. */
function splitWords(text) {
  return String(text || '')
    .toLowerCase()
    .replace(/[^\w\s가-힣]/g, ' ')
    .split(/\s+/)
    .filter((t) => t.length > 1);
}

/**
 * BM25 재채점용 토큰: 낱말마다 줄기로 바꾼다(질의·문서 같은 규칙 → "서버에서"="서버가"="서버").
 * 낱말 수는 그대로다(1:1 치환) — 문서 길이 보정이 예전과 같은 기준으로 돈다.
 * 2026-10-03 실측으로 버린 대안: 원래 꼴+줄기 둘 다 내기, 한글 2글자 조각 더하기 — 둘 다 적중률이 떨어졌다.
 */
export function keywordTokens(text) {
  return splitWords(text).map((w) => koreanStem(w) ?? w);
}

/** 질의 낱말 중 문서에 실제로 나온 서로 다른 낱말 수. */
export function matchedTermCount(queryTokens, docTokens) {
  const doc = new Set(docTokens);
  let n = 0;
  for (const q of queryTokens) if (doc.has(q)) n++;
  return n;
}

/** 질의 토큰에서 군말을 뺀다(BM25 질의 쪽에만 쓴다). */
export function dropStopwords(tokens) {
  return tokens.filter((t) => !STOPWORDS.has(t));
}

/**
 * 색인 검색(FTS)용 줄기 질의 문자열 — 조사·어미를 떼고 군말을 뺀 낱말을 공백으로 잇는다.
 * ("다낭에서 해산물 저녁집 예약은 어떻게 하라고 했었나" → "다낭 해산물 저녁집 예약")
 * 한글 낱말에서 뗀 것이 하나도 없으면 null — 원문 질의와 같으므로 색인을 한 번 더 찌를 이유가 없다
 * (영어/코드만 있는 질의는 기존 경로 그대로 — 회귀 방지).
 *
 * 퍼지 질의("줄기로 시작 + 뒤 2글자")는 쓰지 않는다(2026-10-03 실측): 펼쳐진 드문 변형마다 따로
 * 희소도(IDF) 가산을 받아 점수가 뒤틀렸다 — 정답 청크가 정확 일치 4위 → 퍼지 209위.
 */
export function stemmedQuery(query) {
  const out = [];
  let changed = false;
  for (const w of splitWords(query)) {
    if (STOPWORDS.has(w)) { changed = true; continue; }
    const stem = koreanStem(w);
    if (stem && STOPWORDS.has(stem)) { changed = true; continue; }
    if (stem) changed = true;
    out.push(stem ?? w);
  }
  if (!changed || out.length === 0) return null;
  return [...new Set(out)].join(' ');
}
